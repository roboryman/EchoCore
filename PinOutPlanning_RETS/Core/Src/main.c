/* USER CODE BEGIN 4 */
static void CDC_TX_Buffer_Init(void)
{
	uint16_t version	= 0x0101; // LSB first for memcpy
	uint32_t eeg_data_start = 0xAAAAAAAA; // LSB first for memcpy
	uint32_t imu_data_start = 0x55555555; // LSB first for memcpy

	// Reset to all 0x00
	memset(UserTxBufferFS, 0, sizeof(UserTxBufferFS));

	/* Initialize header and footer */
	UserTxBufferFS[0] = 0xAA;								// Frame Start
	strcpy((char *)&UserTxBufferFS[1], "GALAHAD LABS");		// Vendor
	strcpy((char *)&UserTxBufferFS[13], "ECHOCORE");		// Product
	memcpy(&UserTxBufferFS[21], &version, 2);				// HW/FW Version
	memcpy(&UserTxBufferFS[27], &eeg_data_start, 4);		// EEG Data Start
	/*
	 * EEG Data
	 */
	memcpy(&UserTxBufferFS[39], &imu_data_start, 4);		// IMU Data Start
	UserTxBufferFS[57] = 0x55;								// Frame End
}


void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
	if(GPIO_Pin == IMU_INT1_Pin) // PB12
	{
		imu_int1_flag = 1;
		PDEBUG("INT1 Triggered\r\n");
		#if defined(FIFO_WM_INT)
			#if defined(USE_BMI323)
			bmi323_fifo_ready = 1;
			#endif
		#endif
	}
	else if(GPIO_Pin == IMU_INT2_Pin) // PA9
	{
		// Conflicts with SPI2 CSN...
		imu_int2_flag = 1;
		PDEBUG("INT2 Triggered\r\n");
	}
	else if(GPIO_Pin == ADC_INT_Pin)
	{
		adc_flag = 1;
		//PDEBUG("ADC INT Triggered\r\n");
	}
}


